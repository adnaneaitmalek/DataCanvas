import { readFile } from 'node:fs/promises'
import { Buffer } from 'node:buffer'
import { expect, test } from '@playwright/test'
import type { Page } from '@playwright/test'
import { acceptExclusions, editColumns, reviewAction, showAllColumns, waitForImport } from './import-flow'

async function importCsv(page: Page, data: string, name = 'release.csv') {
  await page.goto('/#/import')
  await page.locator('input[type=file]').setInputFiles({ name, mimeType: 'text/csv', buffer: Buffer.from(data) })
  await waitForImport(page)
  if (await page.locator('.workspace').isVisible()) await editColumns(page).click()
  await showAllColumns(page)
}

const build = reviewAction
const applySchema = (page: Page) => page.getByRole('button', { name: 'Apply changes' })
const filterToggle = (page: Page) => page.getByRole('button', { name: /^Filters/ })
const conditionColumn = (page: Page) => page.getByRole('combobox', { name: 'Filter column' })
const operator = (page: Page) => page.getByRole('combobox', { name: 'Operator' })
const choice = (page: Page) => page.getByRole('combobox', { name: 'Value', exact: true })
const apply = (page: Page) => page.getByRole('button', { name: 'Apply filter' })
const tab = (page: Page, name: 'Data table' | 'Overview') => page.getByRole('button', { name, exact: true })
const schemaRow = (page: Page, name: string) => page.locator('.schema-row').filter({ has: page.getByRole('heading', { name, exact: true }) })

async function download(page: Page, name: string) {
  await page.locator('.export-menu summary').click()
  const [file] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name, exact: true }).click()])
  return file
}

test('ambiguous CSV requires delimiter confirmation and preserves decimal commas in the exported source', async ({ page }) => {
  await importCsv(page, 'Region;Revenue, EUR\nWest;12,50\nEast;8,75')
  await expect(page.getByRole('alert')).toContainText('Comma and Semicolon are plausible delimiters')
  await expect(build(page)).toBeDisabled()
  await page.getByRole('combobox', { name: 'Delimiter' }).selectOption(';')
  await expect(schemaRow(page, 'Revenue, EUR').getByText('€12.50', { exact: true })).toBeVisible()
  await expect(page.getByRole('combobox', { name: 'Delimiter' })).toHaveValue(';')
  await build(page).click()
  await expect(page.locator('.stat-card').getByText('€21.25', { exact: true })).toBeVisible()
  const rows = await download(page, 'Filtered rows (CSV)')
  expect((await readFile(await rows.path(), 'utf8')).trim()).toBe('Region,"Revenue, EUR"\r\nWest,"12,50"\r\nEast,"8,75"')
})

test('short CSV rows cannot silently select a delimiter that changes amounts', async ({ page }) => {
  await importCsv(page, 'Region;Revenue, EUR\nWest;12,50\nEast;8,75\nDepot, North\nDepot, East\nDepot, South\nDepot, West', 'delimiter-short-rows.csv')
  await expect(page.getByRole('alert')).toContainText('Choose a delimiter')
  await expect(build(page)).toBeDisabled()
  await page.getByRole('combobox', { name: 'Delimiter' }).selectOption(';')
  await expect(page.locator('.schema-row')).toHaveCount(2)
  await expect(page.getByText('4 short rows were padded with missing cells.')).toBeVisible()
  await build(page).click()
  await page.getByRole('combobox', { name: 'Aggregation' }).selectOption('sum')
  await expect(page.locator('.featured-stat').getByText('€21.25', { exact: true })).toBeVisible()
  await expect(page.getByText('6 rows · 2 columns')).toBeVisible()
  const rows = await download(page, 'Filtered rows (CSV)')
  expect((await readFile(await rows.path(), 'utf8')).trim().split('\r\n')).toEqual([
    'Region,"Revenue, EUR"', 'West,"12,50"', 'East,"8,75"', '"Depot, North",', '"Depot, East",', '"Depot, South",', '"Depot, West",',
  ])
})

test('currency correction excludes conflicting and unmarked USD amounts and keeps normalized exports in EUR', async ({ page }) => {
  await importCsv(page, 'Region,Revenue (USD)\nEast,EUR 10\nWest,EUR 20\nEast,USD 500\nWest,700')
  await page.getByRole('combobox', { name: 'Type for Revenue (USD)' }).selectOption('currency')
  await page.getByRole('combobox', { name: 'Currency for Revenue (USD)' }).selectOption('EUR')
  await expect(page.getByText('1 unmarked amount is excluded because the source column declares USD.')).toBeVisible()
  await acceptExclusions(page)
  await build(page).click()
  await expect(page.locator('.stat-card').getByText('€30.00', { exact: true })).toBeVisible()
  await expect(page.getByRole('combobox', { name: 'Metric', exact: true }).locator('option:checked')).toHaveText('Revenue (EUR)')
  await filterToggle(page).click()
  await conditionColumn(page).selectOption({ label: 'Revenue (EUR)' })
  await operator(page).selectOption('present')
  await apply(page).click()
  await expect(page.getByText('2 of 4 rows', { exact: true })).toBeVisible()
  const chart = await download(page, 'Chart values (CSV)')
  expect((await readFile(await chart.path(), 'utf8')).trim().split('\r\n')).toEqual([
    'Region,Total revenue (EUR),Records,Valid values', 'West,20,1,1', 'East,10,1,1',
  ])
  await tab(page, 'Data table').click()
  const interpreted = await download(page, 'Table results (CSV)')
  expect((await readFile(await interpreted.path(), 'utf8')).trim()).toBe('Region,Revenue (EUR)\r\nEast,10\r\nWest,20')
  await page.getByLabel('Source values').check()
  const source = await download(page, 'Table results (CSV)')
  expect((await readFile(await source.path(), 'utf8')).trim()).toBe('Region,Revenue (USD)\r\nEast,EUR 10\r\nWest,EUR 20')
  await page.getByRole('link', { name: 'Edit columns' }).click()
  await showAllColumns(page)
  await page.getByRole('checkbox', { name: 'Treat unmarked amounts as EUR' }).check()
  await expect(schemaRow(page, 'Revenue (USD)').getByText('€700.00', { exact: true })).toBeVisible()
  await acceptExclusions(page)
  await applySchema(page).click()
  await expect(page.getByRole('button', { name: 'Confirm export scope' })).toBeVisible()
  await tab(page, 'Overview').click()
  await expect(page.locator('.stat-card').getByText('€730.00', { exact: true })).toBeVisible()
})

