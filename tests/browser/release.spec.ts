test('the PNG, PDF and accessible HTML preserve all 16 conditions in the export', async ({ page }, info) => {
  const regions = Array.from({ length: 15 }, (_, index) => `Region ${index + 1}`)
  await importCsv(page, 'Region,Revenue\n' + regions.map(region => `${region},5`).join('\n') + '\nFinal,1200\nExcluded,4')
  await build(page).click()
  await filterToggle(page).click()
  for (const [index, region] of regions.entries()) {
    await choice(page).selectOption(region)
    await apply(page).click()
    if (index === 1) await page.getByRole('combobox', { name: 'Combine conditions' }).selectOption('any')
  }
  await conditionColumn(page).selectOption({ label: 'Revenue' })
  await operator(page).selectOption('gt')
  await page.getByRole('textbox', { name: 'Value', exact: true }).fill('999')
  await apply(page).click()
  await expect(page.getByText('16 of 17 rows', { exact: true })).toBeVisible()

  const image = await download(page, 'Dashboard image (PNG)')
  const png = await readFile(await image.path())
  expect(png.readUInt32BE(20)).toBeGreaterThanOrEqual((780 + 82 + 16 * 22) * 2)
  await image.saveAs(info.outputPath('many-conditions.png'))
  const pdf = await download(page, 'Dashboard report (PDF)')
  expect((await readFile(await pdf.path())).includes('/Count 2')).toBe(true)
  await pdf.saveAs(info.outputPath('many-conditions.pdf'))
  const report = await download(page, 'Accessible report (HTML)')
  const tab = await page.context().newPage()
  await tab.setContent(await readFile(await report.path(), 'utf8'))
  await expect(tab.getByRole('heading', { name: 'Applied conditions' })).toBeVisible()
  const conditions = tab.getByRole('list').getByRole('listitem')
  await expect(conditions).toHaveCount(16)
  await expect(conditions.last()).toHaveText('Revenue greater than 999')
  await expect(tab.getByRole('table').first()).toBeVisible()
})
